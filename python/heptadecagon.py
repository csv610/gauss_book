# Gauss periods
# ======================================================================

def gaussian_periods(p: int, length: int) -> List[complex]:
    """Compute Gaussian periods for prime p.
    
    Periods of given length are sums of roots of unity with indices
    in the same coset of the subgroup of (Z/pZ)* generated by g^length.
    """
    g = primitive_root(p)
    zeta = cmath.exp(2j * math.pi / p)
    
    # Generate all powers of g modulo p
    powers = []
    cur = 1
    for _ in range(p - 1):
        powers.append(cur)
        cur = (cur * g) % p
    
    periods = []
    for start in range(length):
        period = sum(zeta**powers[start + k*length] for k in range((p-1)//length))
        periods.append(period)
    
    return periods


def cos_2pi_over_17_value() -> float:
    """Numerical value of cos(2π/17)."""
    return math.cos(2 * math.pi / 17)


def constructible_ngons(limit: int = 100) -> List[int]:
    """List of n for which regular n-gon is constructible.

    n = 2^k * p1 * p2 * ... * pm where pi are distinct Fermat primes.
    """
    if limit <= 0:
        return []
    fermat_primes = [3, 5, 17, 257, 65537]
    constructible = set()

    for k in range(int(math.log2(limit)) + 2):
        base = 2 ** k
        if base > limit:
            break
        
        # Add base
        if base <= limit:
            constructible.add(base)
        
        # Multiply by products of Fermat primes
        def add_products(current, start_idx):
            if current > limit:
                return
            if current > 0:
                constructible.add(current)
            for i in range(start_idx, len(fermat_primes)):
                add_products(current * fermat_primes[i], i + 1)
        
        add_products(base, 0)
    
    return sorted(constructible)


def fermat_primes() -> List[int]:
    """Known Fermat primes."""
    return [3, 5, 17, 257, 65537]


def is_fermat_prime(n: int) -> bool:
    """Check if n is a known Fermat prime."""
    return n in [3, 5, 17, 257, 65537]


def is_constructible(n: int) -> bool:
    """Check if regular n-gon is constructible."""
    # Remove factors of 2
    while n % 2 == 0:
        n //= 2
    
    # Check if remaining is product of distinct Fermat primes
    for p in [3, 5, 17, 257, 65537]:
        if n % p == 0:
            n //= p
            if n % p == 0:  # not distinct
                return False
    
    return n == 1


