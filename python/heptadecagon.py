def heptadecagon_exact() -> dict:
    """Exact expressions for 17-gon construction."""
    sqrt17 = math.sqrt(17)
    
    # Gaussian periods of length 8
    eta1 = (-1 + sqrt17) / 2
    eta2 = (-1 - sqrt17) / 2
    
    # Periods of length 4
    # μ1 + μ2 = η1, μ1*μ2 = -1
    # μ3 + μ4 = η2, μ3*μ4 = -1
    sqrt_eta1_sq_4 = math.sqrt(eta1**2 + 4)
    mu1 = (eta1 + sqrt_eta1_sq_4) / 2
    mu2 = (eta1 - sqrt_eta1_sq_4) / 2
    
    sqrt_eta2_sq_4 = math.sqrt(eta2**2 + 4)
    mu3 = (eta2 + sqrt_eta2_sq_4) / 2
    mu4 = (eta2 - sqrt_eta2_sq_4) / 2
    
    # Periods of length 2
    # ν1 + ν2 = μ1, ν1*ν2 = μ3
    # ν3 + ν4 = μ2, ν3*ν4 = μ4
    # ν5 + ν6 = μ3, ν5*ν6 = μ1
    # ν7 + ν8 = μ4, ν7*ν8 = μ2
    
    # These give the cosines
    cos_2pi_17 = mu1 / 2
    cos_4pi_17 = mu2 / 2
    cos_8pi_17 = mu3 / 2
    cos_16pi_17 = mu4 / 2
    
    return {
        'eta1': eta1, 'eta2': eta2,
        'mu1': mu1, 'mu2': mu2, 'mu3': mu3, 'mu4': mu4,
        'cos_2pi_17': cos_2pi_17,
        'cos_4pi_17': cos_4pi_17,
        'cos_8pi_17': cos_8pi_17,
        'cos_16pi_17': cos_16pi_17,
    }


